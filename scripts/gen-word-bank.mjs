const uniq = (arr) => [...new Set(arr)]

const valorant = uniq(
  valorantRaw
    .map((w) => w.toLowerCase().replace(/[^a-z]/g, ''))
    .filter((w) => w.length >= 3 && w.length <= 18),
).sort()

const fiveLetter = uniq(five).sort()

function fmt(arr) {
  const lines = []
  for (let i = 0; i < arr.length; i += 10) {
    lines.push(
      '  ' +
        arr
          .slice(i, i + 10)
          .map((w) => JSON.stringify(w))
          .join(','),
    )
  }
  return lines.join(',\n') + ','
}

const out = `/** Shared word banks (Valorant + 5-letter) for Wordle, Hangman, etc. */
export const VALORANT_WORDS = [
${fmt(valorant)}
] as const

export const FIVE_LETTER_WORDS = [
${fmt(fiveLetter)}
] as const
`

